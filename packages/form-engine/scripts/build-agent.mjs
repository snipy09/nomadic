/**
 * Bundles the in-page form agent (src/agent/entry.ts) into one self-contained IIFE and writes
 * it as a string constant to src/agent/bundle.generated.ts. The Android app hands that string
 * to the WebView (document-start script, every frame); tests inject the same string.
 *
 *   npm run build:agent -w @job-automator/form-engine          # write the bundle
 *   npm run check:agent -w @job-automator/form-engine          # exit 1 when it is stale
 */
import { build } from 'esbuild';
import { createHash } from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'src/agent/bundle.generated.ts');

export async function buildAgentSource() {
  const result = await build({
    entryPoints: [path.join(root, 'src/agent/entry.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    // Android System WebView is evergreen; Chrome 90 still covers old devices that stopped updating.
    target: ['chrome90'],
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  });
  const js = result.outputFiles[0].text.trim();
  for (const banned of ['require(', 'process.', 'Buffer', 'eval(', 'new Function']) {
    if (js.includes(banned)) throw new Error(`agent bundle must not use ${banned}`);
  }
  // Re-running the agent in the same document is a no-op (install() checks window.__nomadicAgent).
  return js;
}

export function renderModule(js) {
  const sha = createHash('sha256').update(js).digest('hex').slice(0, 16);
  return `// Generated by scripts/build-agent.mjs from src/agent/*.ts. Do not edit; run \`npm run build:agent -w @job-automator/form-engine\`.
/* eslint-disable */
export const AGENT_SCRIPT_SHA = '${sha}';
export const AGENT_SCRIPT = ${JSON.stringify(js)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mod = renderModule(await buildAgentSource());
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (cur !== mod) {
      console.error('src/agent/bundle.generated.ts is stale: run npm run build:agent -w @job-automator/form-engine');
      process.exit(1);
    }
    console.log('agent bundle is up to date');
  } else {
    fs.writeFileSync(outFile, mod);
    console.log(`wrote ${path.relative(process.cwd(), outFile)} (${(mod.length / 1024).toFixed(1)} KB)`);
  }
}
