export const slugify = (name: string): string =>
  name
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 64);

const FEED_SLUGS = new Set(COMPANIES.map((c) => c.slug));

export const INDIA_COMPANIES: IndiaCompany[] = (Object.entries(GROUPS) as [CompanyCategory, Row[]][]).flatMap(([category, rows]) =>
  rows
    .map(([name, aliases = [], boardHints = []]) => ({ slug: slugify(name), name, category, aliases, boardHints }))
    .filter((c) => !FEED_SLUGS.has(c.slug))
);

/** Board slugs worth probing for a company: hints first, then the name squashed and hyphenated. */
export function boardSlugsFor(company: { name: string; boardHints?: string[] }): string[] {
  const base = company.name
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/['’.]/g, '')
    .replace(/\b(technologies|technology|systems|software|labs|private|limited|ltd|inc|group)\b/g, ' ')
    .trim();
  const words = base.split(/[^a-z0-9]+/).filter(Boolean);
  const out = [...(company.boardHints ?? []), words.join(''), words.join('-')];
  return [...new Set(out.filter((s) => s.length >= 2))];
}
