// Writes packages/supabase/baseline/content_seed.sql from seed/bundle.json: an idempotent upsert of the
// Learn content (skills, prerequisites, role families, role weights, resources, lessons, practice items)
// for pasting into the Supabase SQL editor. Same rows as scripts/seed.ts (which needs the service-role key).
// Resources keep any link-check status already stored. No blank lines (the SQL editor splits on them).
//   node packages/learning/scripts/seed-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const b = JSON.parse(readFileSync(resolve(here, '../seed/bundle.json'), 'utf8'));
const out = resolve(here, '../../supabase/baseline/content_seed.sql');

// Dollar-quoted strings (no backslash escapes, which the Supabase editor's statement splitter misreads);
// newlines become chr(10) so every value stays on one line (the editor also splits on blank lines).
const TAG = '$s$';
const dq = (v) => {
  if (v.includes(TAG)) throw new Error('value contains the dollar-quote tag');
  return `${TAG}${v}${TAG}`;
};
const q = (v) => (v === null || v === undefined ? 'NULL' : String(v).split(/\r?\n/).map(dq).join(' || chr(10) || '));
const arr = (a) => `ARRAY[${(a ?? []).map(q).join(',')}]::text[]`;
const num = (v) => (v === null || v === undefined ? 'NULL' : Number(v));
const bool = (v) => (v ? 'TRUE' : 'FALSE');
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

function upsert(table, cols, rows, conflict, update) {
  if (!rows.length) return '';
  const set = update.length ? `DO UPDATE SET ${update.map((c) => `${c} = EXCLUDED.${c}`).join(', ')}` : 'DO NOTHING';
  return `INSERT INTO public.${table} (${cols.join(', ')}) VALUES\n${rows.map((r) => `(${r.join(', ')})`).join(',\n')}\nON CONFLICT (${conflict}) ${set};\n`;
}

const parts = [
  `-- Nomadic Learn content seed ${b.version} (generated by packages/learning/scripts/seed-sql.mjs). Paste and Run.`,
  'BEGIN;',
  upsert('skills', ['id', 'name', 'description', 'category', 'level', 'estimated_hours', 'aliases', 'patterns'],
    b.skills.map((s) => [q(s.id), q(s.name), q(s.description), q(s.category), num(s.level), num(s.estimated_hours), arr(s.aliases), arr(s.patterns)]),
    'id', ['name', 'description', 'category', 'level', 'estimated_hours', 'aliases', 'patterns']),
  upsert('skill_prerequisites', ['skill_id', 'prerequisite_id', 'strength'],
    b.prerequisites.map((p) => [q(p.skill_id), q(p.prerequisite_id), q(p.strength)]), 'skill_id, prerequisite_id', ['strength']),
  upsert('role_families', ['id', 'name', 'description', 'legacy_roadmap_ids', 'example_titles'],
    b.roles.map((r) => [q(r.id), q(r.name), q(r.description), arr(r.legacy_roadmap_ids), arr(r.example_titles)]),
    'id', ['name', 'description', 'legacy_roadmap_ids', 'example_titles']),
  upsert('role_skills', ['role_id', 'skill_id', 'weight'],
    b.role_skills.map((r) => [q(r.role_id), q(r.skill_id), num(r.weight)]), 'role_id, skill_id', ['weight']),
  upsert('learning_resources', ['id', 'title', 'url', 'provider', 'type', 'duration_minutes', 'skill_ids', 'level', 'quality', 'is_free', 'source'],
    b.resources.map((r) => [q(r.id), q(r.title), q(r.url), q(r.provider), q(r.type), num(r.duration_minutes), arr(r.skill_ids), num(r.level), num(r.quality), bool(r.is_free), q(r.source)]),
    'id', []),
  upsert('lessons', ['id', 'skill_id', 'title', 'summary_md', 'key_points', 'resource_ids', 'estimated_minutes', 'is_core', 'status', 'ai_drafted', 'version'],
    b.lessons.map((l) => [q(l.id), q(l.skill_id), q(l.title), q(l.summary_md), arr(l.key_points), arr(l.resource_ids), num(l.estimated_minutes), bool(l.is_core), q(l.status), bool(l.ai_drafted), num(l.version)]),
    'id', []),
  upsert('practice_items', ['id', 'skill_id', 'lesson_id', 'kind', 'difficulty', 'company_tags', 'body', 'status', 'ai_drafted', 'version'],
    b.practice_items.map((p) => [q(p.id), q(p.skill_id), q(p.lesson_id), q(p.kind), q(p.difficulty), arr(p.company_tags), json(p), q(p.status), bool(p.ai_drafted), num(p.version)]),
    'id', []),
  'COMMIT;',
];
writeFileSync(out, parts.filter(Boolean).join('\n').split('\n').filter((l) => l.trim() !== '').join('\n') + '\n');
console.log(`wrote ${out}`);
